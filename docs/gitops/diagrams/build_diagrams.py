class SVG:
    def __init__(self,title,desc):
        self.parts=[f'''<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-labelledby="title desc">
<title id="title">{escape(title)}</title><desc id="desc">{escape(desc)}</desc>
<defs>''']
        for name,color in [('gray',LINE),('blue',BLUE_LINE),('orange',ORANGE_LINE)]:
            self.parts.append(f'<marker id="arrow-{name}" markerWidth="10" markerHeight="10" refX="8" refY="5" orient="auto" markerUnits="userSpaceOnUse"><path d="M0 0 L9 5 L0 10 Z" fill="{color}"/></marker>')
        self.parts.append(f'</defs><rect width="{W}" height="{H}" fill="white"/><g font-family="{FONT}" fill="{INK}">')
    def rect(self,x,y,w,h,stroke=BORDER,fill='white',r=0,sw=1.5):
        self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"/>')
    def text(self,x,y,label,size=24,weight=400,color=INK,anchor='start'):
        self.parts.append(f'<text x="{x}" y="{y}" font-size="{size}" font-weight="{weight}" fill="{color}" text-anchor="{anchor}">{escape(label)}</text>')
    def path(self,d,color=LINE,width=2.4,arrow=None,dash=None):
        extra=(f' marker-end="url(#arrow-{arrow})"' if arrow else '')+(f' stroke-dasharray="{dash}"' if dash else '')
        self.parts.append(f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{width}" stroke-linecap="square" stroke-linejoin="miter"{extra}/>')
    def icon(self,name,x,y,w=72,h=None):
        h=h or w
        data=base64.b64encode((ASSETS/f'{name}.svg').read_bytes()).decode()
        self.parts.append(f'<image x="{x}" y="{y}" width="{w}" height="{h}" preserveAspectRatio="xMidYMid meet" xlink:href="data:image/svg+xml;base64,{data}"/>')
    def pill(self,x,y,w,label,fill=BLUE_LIGHT,color=BLUE,size=19):
        self.rect(x,y,w,34,stroke='none',fill=fill,r=17)
        self.text(x+w/2,y+24,label,size,700,color,'middle')
    def git(self,x,y,size=78):
        self.parts.append(f'<g transform="translate({x},{y}) scale({size/80})"><rect x="11" y="11" width="58" height="58" rx="4" fill="#F15B35" transform="rotate(45 40 40)"/><path d="M27 15 L27 51 M27 25 L52 49" fill="none" stroke="white" stroke-width="5"/><circle cx="27" cy="24" r="6" fill="white"/><circle cx="27" cy="53" r="6" fill="white"/><circle cx="53" cy="50" r="6" fill="white"/></g>')
    def queue(self,x,y,size=78):
        self.parts.append(f'<g transform="translate({x},{y}) scale({size/80})"><rect width="80" height="80" rx="4" fill="#E80083"/><path d="M14 30 H57 L65 40 L57 50 H14" fill="none" stroke="white" stroke-width="2.5"/><circle cx="26" cy="40" r="6" fill="none" stroke="white" stroke-width="2.5"/><circle cx="45" cy="40" r="6" fill="none" stroke="white" stroke-width="2.5"/></g>')
    def file(self,x,y):
        self.parts.append(f'<g transform="translate({x},{y})" fill="none" stroke="{BLUE_LINE}" stroke-width="2"><path d="M0 0 H20 L29 9 V34 H0 Z M20 0 V9 H29 M6 16 H23 M6 23 H23"/></g>')
    def finish(self,name):
        self.parts.append('</g></svg>')
        (OUT/name).write_text('\n'.join(self.parts))


